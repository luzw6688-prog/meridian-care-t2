export type MessageKey = keyof (typeof messages)["en"];

let currentLanguage: Language = "en";

export function t(key: MessageKey): string {
  return messages[currentLanguage][key];
}

export function applyLanguage(language: Language): void {
  currentLanguage = language;
  document.documentElement.lang = language;
  document.title = t("page.title");
  document
    .querySelector<HTMLMetaElement>('meta[name="description"]')
    ?.setAttribute("content", t("page.description"));

  document.querySelectorAll<HTMLElement>("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n as MessageKey | undefined;
    if (key) element.textContent = t(key);
  });
  document.querySelectorAll<HTMLElement>("[data-i18n-alt]").forEach((element) => {
    const key = element.dataset.i18nAlt as MessageKey | undefined;
    if (key) element.setAttribute("alt", t(key));
  });
  document.querySelectorAll<HTMLElement>("[data-i18n-aria-label]").forEach((element) => {
    const key = element.dataset.i18nAriaLabel as MessageKey | undefined;
    if (key) element.setAttribute("aria-label", t(key));
  });

}
